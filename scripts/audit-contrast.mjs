#!/usr/bin/env node
/**
 * Rendered-page contrast audit -- every visible text node, its computed colour
 * against its actual painted background, on every screen, in both themes.
 *
 * Token-pair checks (tests/tokens.test.ts) prove the PALETTE passes. They cannot
 * see a combination the palette never listed: white on a gradient's light end,
 * a channel colour reused as an avatar fill. Those were the Sept 28 failures,
 * and only this found them.
 *
 * Needs the dev server (npm run dev) and Google Chrome.
 *   node scripts/audit-contrast.mjs            -> writes docs/CONTRAST.md
 *
 * The in-page probe lives in scripts/contrast-probe.js. It skips text inside
 * disabled controls (WCAG-exempt), .gr-sr-only, and anything at opacity < 1
 * (hover-revealed controls). Gradients are checked at EVERY stop, so the worst
 * end is what counts.
 */
import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = process.env.GROWTH_URL ?? 'http://127.0.0.1:5173/Growth/';
const CHROME = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const PROBE = readFileSync(resolve(ROOT, 'scripts/contrast-probe.js'), 'utf8');
const SCREENS = [
  'v=overview', 'v=channels&c=meta', 'v=campaigns', 'v=campaigns&p=c1', 'v=campaigns&p=c1&s=c1a',
  'v=ads', 'v=decisions', 'v=reports', 'v=notifications', 'v=settings',
];

const port = 9335;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const chrome = spawn(CHROME, ['--headless=new', '--disable-gpu', `--remote-debugging-port=${port}`,
  `--user-data-dir=/tmp/growth-contrast-${Date.now()}`, '--window-size=1512,1400', 'about:blank'], { stdio: 'ignore' });

let ws;
for (let i = 0; i < 50 && !ws; i++) {
  try {
    const page = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find((t) => t.type === 'page');
    if (page) ws = new WebSocket(page.webSocketDebuggerUrl);
  } catch { /* not up yet */ }
  await sleep(200);
}
/* The socket can open during the retry sleep above -- waiting for an 'open'
   event that has already fired would hang forever. Check the state first. */
if (ws.readyState !== WebSocket.OPEN) await new Promise((r) => ws.addEventListener('open', r));
let id = 0;
const pending = new Map();
ws.addEventListener('message', (e) => {
  const m = JSON.parse(e.data);
  if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); }
});
const send = (method, params = {}) => new Promise((r) => {
  const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params }));
});
await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1512, height: 1400, deviceScaleFactor: 1, mobile: false });

const results = {};
for (const theme of ['light', 'dark']) {
  await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: theme }] });
  for (const s of SCREENS) {
    await send('Page.navigate', { url: `${BASE}?${s}` });
    await sleep(1800);
    await send('Runtime.evaluate', {
      expression: `localStorage.setItem('growth.theme','${theme}'); document.documentElement.dataset.theme='${theme}'`,
    });
    await sleep(200);
    const r = await send('Runtime.evaluate', {
      expression: `(async()=>{${PROBE}})()`, awaitPromise: true, returnByValue: true,
    });
    results[`${theme} · ${s}`] = r.result?.result?.value ?? [];
  }
}
chrome.kill();

const total = Object.values(results).reduce((a, f) => a + f.length, 0);
const lines = [
  '# Contrast audit — rendered',
  '',
  `Generated by \`scripts/audit-contrast.mjs\` on ${new Date().toISOString().slice(0, 10)}. `
    + 'Every visible text node on each screen, measured against its painted background (every gradient '
    + 'stop). AA: 4.5:1 for text, 3:1 for large text. Token-level pairs are enforced on every test run '
    + 'by `tests/tokens.test.ts`.',
  '',
  `**${total === 0 ? '✅ 0 failures' : `❌ ${total} failures`}** across ${SCREENS.length} screens × 2 themes.`,
  '',
  '| Theme · screen | Failures |',
  '|---|---|',
  ...Object.entries(results).map(([k, f]) => `| ${k} | ${f.length} |`),
  '',
];
for (const [k, f] of Object.entries(results)) {
  for (const x of f) {
    lines.push(`- ${k}: **${x.ratio}:1** (needs ${x.need}) "${x.text}" \`${x.cls}\` ${x.fg} on ${x.bg}`);
  }
}
writeFileSync(resolve(ROOT, 'docs/CONTRAST.md'), lines.join('\n') + '\n');
console.log(total === 0 ? '0 failures' : `${total} failures`, '-> docs/CONTRAST.md');
process.exit(total === 0 ? 0 : 1);
